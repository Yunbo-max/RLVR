#!/usr/bin/env python3
"""Original (not post-hoc Shapley) EED relevance/repair audit for JToX.

The submitted lexical relevance was generated by PBPF:
  change = unified_diff(original, correction)  # fallback=correction
  descriptor_i = JSON{input, expected, actual, stderr, outcome}
  q = FrozenTextEncoder(256)(change)
  h_i = FrozenTextEncoder(256)(descriptor_i)
  relevance_i = cosine_relevance_weights(q, h, kappa=16)
These execution descriptors describe the PRE-CORRECTION public tests.
The revised code is subsequently executed to produce after_outcomes.

Without archived complete original pre-correction execution rows, merely
having saved relevance scores does not prove the exact descriptor features.
This audit records coverage and can optionally recompute with the exact
pinned old PBPF code. It reports the JToX counterexample and partially
correct corrections with nonzero supervised weight.
"""
from __future__ import annotations

import argparse
from collections import Counter,defaultdict
import difflib
import hashlib
import json
from pathlib import Path
import subprocess
import sys

import numpy as np

from eesd.evidence import transition_categories
from eesd.token_aware import original_program
from eesd.registry import OUTCOMES
import prepare_submitted_dirichlet_rebuttal_weights as eed

PBPF_PIN="0200283849274b49e303638b91f142acd8bba984"
FEATURES=("input","expected","actual","stderr","outcome")


def _sha(path:Path)->str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _public_descriptors(row:dict)->list[dict]|None:
    prompt=row.get("prompt")
    if not isinstance(prompt,str) or "\n" not in prompt:
        return None
    try:obj=json.loads(prompt.split("\n",1)[1].strip())
    except (json.JSONDecodeError,TypeError):return None
    if not isinstance(obj,dict):return None
    data=obj.get("public_executions")
    if not isinstance(data,list) or not data or not all(
        isinstance(t,dict) and all(k in t for k in FEATURES) for t in data
    ):
        return None
    return data


def _pbpf_components(root:Path):
    root=root.resolve()
    if not (root/".git").exists():
        raise ValueError("the original PBPF checkout (with .git) is required")
    head=subprocess.run(["git","rev-parse","HEAD"],cwd=root,check=True,
                        text=True,capture_output=True).stdout.strip()
    if head!=PBPF_PIN:
        raise ValueError(f"original signed-hash code is not pinned: {head}")
    sys.path.insert(0,str(root/"src"))
    from pbpf.real_gate import FrozenTextEncoder
    from pbpf.eesd.evidence import cosine_relevance_weights
    return FrozenTextEncoder,cosine_relevance_weights


def audit(path:Path,*,pbpf_root:Path|None=None)->dict:
    rows=[json.loads(l) for l in path.read_text().split("\n") if l.strip()]
    if not rows:raise ValueError("empty raw corrections")
    encoder_cls=cosine=None
    if pbpf_root is not None:
        encoder_cls,cosine=_pbpf_components(pbpf_root)
        encode=encoder_cls(256)
    kernel_counts=Counter()
    descriptor_counts=Counter()
    transition_counts=Counter()
    evaluation=Counter()
    by_split=defaultdict(Counter)
    first_failed=[]
    measured=[]
    for row in rows:
        before=eed.to_codes(row,"before_outcomes")
        after=eed.to_codes(row,"after_outcomes")
        if len(before)!=len(after) or len(before)!=len(row.get("relevance",[])):
            raise ValueError("mismatched original correction outcomes/relevance")
        split=row.get("split")
        if split not in ("train","development"):
            raise ValueError("only training/development correction trajectory allowed")
        metric=eed.weights_for_record(before,after,row["relevance"])
        statuses=transition_categories(before,after)
        types=["fix","regression","preserve","unresolved"]
        counts=Counter(types[int(z)] for z in statuses)
        transition_counts.update(counts)
        passed=sum(x==0 for x in after)
        by_split[split]["rows"]+=1
        by_split[split]["partial_final"]+=int(0<passed<len(after))
        by_split[split]["failed_final"]+=int(passed<len(after))
        by_split[split]["positive_weight"]+=int(metric["adaptive_eed"]>0)
        by_split[split]["positive_weight_but_not_fully_correct"]+=int(
            metric["adaptive_eed"]>0 and passed<len(after)
        )
        by_split[split]["post_pass_all_tests"]+=int(passed==len(after))
        evaluation["one_fix_three_unresolved"]+=int(
            len(after)==4 and counts["fix"]==1 and counts["unresolved"]==3
        )
        evaluation["one_fix_three_preserve"]+=int(
            len(after)==4 and counts["fix"]==1 and counts["preserve"]==3
        )
        kernel=row.get("relevance_kernel")
        if isinstance(kernel,dict):
            exact=(kernel.get("type")=="frozen_signed_hash_cosine"
                and kernel.get("dimension")==256
                and kernel.get("strength")==16.
                and kernel.get("query")=="unified_diff(original, correction)"
                and kernel.get("history")=="public execution descriptor only")
            kernel_counts["original_metadata_verified" if exact else
                          "unrecognized_kernel_metadata"]+=1
        else:kernel_counts["missing_kernel_metadata"]+=1
        try:
            original,_=original_program(row)
            kernel_counts["paired_original_recoverable"]+=1
        except ValueError:
            original=None
            kernel_counts["original_source_absent"]+=1
        tests=_public_descriptors(row)
        if tests is None or len(tests)!=len(before):
            descriptor_counts["missing_or_truncated_public_descriptor"]+=1
        else:
            descriptor_counts["complete_five_field_public_descriptor"]+=1
            descriptor_counts["before_outcomes_consistent_with_descriptor"]+=int(
                all(t["outcome"]==OUTCOMES[x] for t,x in zip(tests,before))
            )
        if encoder_cls is not None:
            if original is None or tests is None or len(tests)!=len(before):
                descriptor_counts["cannot_recompute_full_signed_hash"]+=1
                continue
            change="\n".join(difflib.unified_diff(
                original.splitlines(),row["correction"].splitlines(),
                fromfile="before.py",tofile="after.py",lineterm=""))
            if not change.strip():change=row["correction"]
            descriptors=[
                json.dumps({k:t[k] for k in FEATURES},sort_keys=True,ensure_ascii=False)
                for t in tests
            ]
            rel=cosine(encode(change),np.stack([encode(t) for t in descriptors]),16.)
            if np.allclose(rel,row["relevance"],atol=1e-6,rtol=1e-6):
                descriptor_counts["recomputed_relevance_matches_original"]+=1
            else:
                descriptor_counts["recomputed_relevance_mismatch"]+=1
                if len(first_failed)<10:first_failed.append(row.get("trajectory_id"))
            measured.append(float(np.max(np.abs(rel-np.asarray(row["relevance"])))) )
    # Exact reviewer counterexample under the submitted transition utility.
    unresolved=eed.weights_for_record([1,1,1,1],[0,1,1,1],[1.]*4)
    preserved=eed.weights_for_record([1,0,0,0],[0,0,0,0],[1.]*4)
    return {
        "schema":"eesd-submitted-original-descriptor-audit-v1",
        "source_input_sha256":_sha(path),"rows":len(rows),
        "old_method":"four transition labels, signed hash 256, kappa16, alpha0.1, lambda0.5",
        "kernel_generation_source":"yuhanlydia/PBPF/scripts/generate_eesd_corrections.py",
        "kernel_generation_ref":PBPF_PIN,
        "descriptor_source":"PRE-correction public I/O and status fields, not post-correction outcomes",
        "descriptor_fields":list(FEATURES),
        "kernel_metadata":dict(kernel_counts),
        "descriptor_coverage":dict(descriptor_counts),
        "transition_totals":dict(transition_counts),
        "per_split":{s:dict(vals) for s,vals in by_split.items()},
        "one_fix_case_counts":dict(evaluation),
        "jtox_counterexample":{
            "one_fix_three_unresolved_weight":unresolved["adaptive_eed"],
            "one_fix_three_preserved_weight":preserved["adaptive_eed"],
            "weights_equal":abs(unresolved["adaptive_eed"]-preserved["adaptive_eed"])<1e-12,
            "after_public_pass_rate_unresolved":.25,
            "after_public_pass_rate_preserved":1.0
        },
        "full_kernel_recomputation_attempted":pbpf_root is not None,
        "maximum_recomputation_absolute_error":max(measured) if measured else None,
        "first_recomputation_failures":first_failed,
        "limits":[
            "Complete public test descriptors may not be reconstructable from a clipped model prompt.",
            "A similarity kernel is a lexical proxy and its output is not a calibrated causal relevance estimate.",
            "Partially wrong corrections may have positive original EED weight; this is empirical diagnostic, not proof that their updates are beneficial.",
            "This audit does not establish future-outcome label construction or source-disjoint generalization."
        ]
    }


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--corrections",type=Path,required=True)
    p.add_argument("--output",type=Path,required=True)
    p.add_argument("--pbpf-root",type=Path)
    a=p.parse_args()
    if a.output.exists():raise FileExistsError("descriptor audit already exists")
    res=audit(a.corrections,pbpf_root=a.pbpf_root)
    a.output.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_text(json.dumps(res,sort_keys=True,indent=2)+"\n")
    print(json.dumps({"rows":res["rows"],
                      "kernel_metadata":res["kernel_metadata"],
                      "descriptor_coverage":res["descriptor_coverage"],
                      "jtox_counterexample":res["jtox_counterexample"]},indent=2))


if __name__=="__main__":main()
